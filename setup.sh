#!/usr/bin/env bash
# Run once on your computer (needs Node 18+, JDK 17, Android Studio) or by the GitHub workflow.
# Usage: bash setup.sh            (optional: VERSION_CODE=5 VERSION_NAME=1.4 bash setup.sh)
set -euo pipefail

npm ci 2>/dev/null || npm install          # npm ci = exact versions from package-lock.json
npx cap add android

P=android/app/src/main/java/com/dairy/orderapp
R=android/app/src/main/res
mkdir -p "$P" "$R/xml"
rm -f "$P/MainActivity.java"
cp native/*.java "$P/"
cp native/AndroidManifest.xml android/app/src/main/AndroidManifest.xml

# GKhata icon + launch screen replace the default Capacitor ones (generated by tools/make-icons.py)
rm -f "$R"/mipmap-*/ic_launcher*.png "$R"/drawable-v24/ic_launcher_foreground.xml "$R"/drawable/ic_launcher_background.xml
find "$R" -name 'splash.png' -delete
cp -r native/res/. "$R"/

sed -i "s/minSdkVersion = .*/minSdkVersion = 24/" android/variables.gradle      # Keystore encryption needs API 24+

# versionName = shown to people (now fixed at V1 = 1.0.1; change with VERSION_NAME=1.0.2 bash setup.sh)
# versionCode = used by Android to decide "is this an update?" (must go UP with every release, so it still follows the build number)
VC="${VERSION_CODE:-${GITHUB_RUN_NUMBER:-1}}"
VN="${VERSION_NAME:-1.0.1}"
sed -i -E "s/versionCode [0-9]+/versionCode $VC/; s/versionName \"[^\"]*\"/versionName \"$VN\"/" android/app/build.gradle
grep -E "versionCode|versionName" android/app/build.gradle

npx cap sync android
echo "Done. versionCode=$VC versionName=$VN"
echo "Open with: npx cap open android  -> Build > Generate Signed Bundle/APK"
